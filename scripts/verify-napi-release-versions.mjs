#!/usr/bin/env node

import { copyFile, readFile, readdir } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const defaultPackageDir = resolve(scriptDir, "../crates/hearth-napi");
const semverPattern =
  /^(?:0|[1-9]\d*)\.(?:0|[1-9]\d*)\.(?:0|[1-9]\d*)(?:-(?:(?:0|[1-9]\d*|\d*[A-Za-z-][0-9A-Za-z-]*)(?:\.(?:0|[1-9]\d*|\d*[A-Za-z-][0-9A-Za-z-]*))*))?(?:\+(?:[0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*))?$/;
const loaderCheckPattern =
  /const bindingPackageVersion = require\('([^'\r\n]+)\/package\.json'\)\.version\r?\n\s*if \(bindingPackageVersion !== '([^'\r\n]+)' && process\.env\.NAPI_RS_ENFORCE_VERSION_CHECK && process\.env\.NAPI_RS_ENFORCE_VERSION_CHECK !== '0'\) \{\r?\n\s*throw new Error\(`Native binding package version mismatch, expected ([^`\r\n]+) but got \$\{bindingPackageVersion\}\. You can reinstall dependencies to fix this issue\.`\)\r?\n\s*\}/g;

function invariant(condition, message) {
  if (!condition) {
    throw new Error(message);
  }
}

function exactVersion(version, label) {
  invariant(
    typeof version === "string" && semverPattern.test(version),
    `${label} is not an exact SemVer: ${JSON.stringify(version)}`,
  );
  return version;
}

async function readJson(path) {
  const source = await readFile(path, "utf8");
  try {
    return JSON.parse(source);
  } catch (error) {
    throw new Error(`invalid JSON in ${path}: ${error.message}`, { cause: error });
  }
}

export function inspectGeneratedLoader(source, expectedVersion, platformNames = []) {
  invariant(source.includes("/* auto-generated by NAPI-RS */"), "generated loader marker is missing");
  invariant(
    source.includes("import { createRequire } from 'module'"),
    "generated loader is not ESM",
  );
  const declarationCount = source.match(/\bconst bindingPackageVersion = require\(/g)?.length ?? 0;
  const checks = Array.from(source.matchAll(loaderCheckPattern), (match) => ({
    packageName: match[1],
    comparisonVersion: match[2],
    messageVersion: match[3],
  }));
  invariant(checks.length > 0, "generated loader has no package-version guards");
  invariant(
    checks.length === declarationCount,
    `generated loader template drift: parsed ${checks.length} of ${declarationCount} package-version guards`,
  );
  for (const check of checks) {
    invariant(
      check.comparisonVersion === check.messageVersion,
      `generated loader check for ${check.packageName} compares ${check.comparisonVersion} but reports ${check.messageVersion}`,
    );
    invariant(
      check.comparisonVersion === expectedVersion,
      `generated loader check for ${check.packageName} expects ${check.comparisonVersion}, root package is ${expectedVersion}`,
    );
  }
  const checkedPackages = new Set(checks.map((check) => check.packageName));
  for (const name of platformNames) {
    invariant(checkedPackages.has(name), `generated loader has no version check for ${name}`);
  }
  return checks;
}

async function rootManifest(packageDir) {
  const manifest = await readJson(resolve(packageDir, "package.json"));
  exactVersion(manifest.version, "root package version");
  return manifest;
}

export async function stageNapiBuildBindings(packageDir, artifactsDir) {
  const manifest = await rootManifest(packageDir);
  const targets = manifest.napi?.targets;
  invariant(Array.isArray(targets) && targets.length > 0, "root napi.targets is empty");
  invariant(new Set(targets).size === targets.length, "root napi.targets contains duplicates");

  let canonicalLoader;
  let canonicalTypes;
  let canonicalTarget;
  for (const target of targets) {
    invariant(
      typeof target === "string" && /^[0-9A-Za-z._-]+$/.test(target),
      `invalid napi target: ${JSON.stringify(target)}`,
    );
    const artifactDir = resolve(artifactsDir, `bindings-${target}`);
    const [loader, types] = await Promise.all([
      readFile(resolve(artifactDir, "index.js")),
      readFile(resolve(artifactDir, "index.d.ts")),
    ]);
    inspectGeneratedLoader(loader.toString("utf8"), manifest.version);
    if (canonicalLoader === undefined) {
      canonicalLoader = loader;
      canonicalTypes = types;
      canonicalTarget = target;
    } else {
      invariant(loader.equals(canonicalLoader), `index.js differs between ${canonicalTarget} and ${target}`);
      invariant(types.equals(canonicalTypes), `index.d.ts differs between ${canonicalTarget} and ${target}`);
    }
  }

  const committedTypes = await readFile(resolve(packageDir, "index.d.ts"));
  invariant(
    canonicalTypes.equals(committedTypes),
    `generated index.d.ts from ${canonicalTarget} differs from the committed file`,
  );
  await copyFile(
    resolve(artifactsDir, `bindings-${canonicalTarget}`, "index.js"),
    resolve(packageDir, "index.js"),
  );
  return { version: manifest.version, targets: targets.length, canonicalTarget };
}

function sameMembers(left, right) {
  return left.length === right.length && left.every((value, index) => value === right[index]);
}

export async function verifyNapiReleaseVersions(packageDir = defaultPackageDir) {
  const manifest = await rootManifest(packageDir);
  const platformRoot = resolve(packageDir, "npm");
  const [loader, platformEntries] = await Promise.all([
    readFile(resolve(packageDir, "index.js"), "utf8"),
    readdir(platformRoot, { withFileTypes: true }),
  ]);
  const platformDirs = platformEntries
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
  invariant(platformDirs.length > 0, "release has no platform package directories");

  const targetCount = new Set(manifest.napi?.targets ?? []).size;
  invariant(
    targetCount === platformDirs.length,
    `root declares ${targetCount} napi targets but release has ${platformDirs.length} platform packages`,
  );

  const platformManifests = await Promise.all(
    platformDirs.map(async (directory) => ({
      directory,
      manifest: await readJson(resolve(platformRoot, directory, "package.json")),
    })),
  );
  const platformNames = [];
  for (const { directory, manifest: platform } of platformManifests) {
    invariant(
      typeof platform.name === "string" && platform.name.length > 0,
      `platform package ${directory} has no name`,
    );
    invariant(
      platform.version === manifest.version,
      `platform package ${platform.name} is ${platform.version}, root package is ${manifest.version}`,
    );
    platformNames.push(platform.name);
  }
  platformNames.sort();
  invariant(
    new Set(platformNames).size === platformNames.length,
    "release contains duplicate platform package names",
  );

  const optionalDependencies = manifest.optionalDependencies;
  invariant(
    optionalDependencies && typeof optionalDependencies === "object" && !Array.isArray(optionalDependencies),
    "root package has no optionalDependencies object",
  );
  const optionalNames = Object.keys(optionalDependencies).sort();
  invariant(
    sameMembers(optionalNames, platformNames),
    `optionalDependencies [${optionalNames.join(", ")}] do not match platform packages [${platformNames.join(", ")}]`,
  );
  for (const name of platformNames) {
    invariant(
      optionalDependencies[name] === manifest.version,
      `optional dependency ${name} uses ${optionalDependencies[name]}, expected exact version ${manifest.version}`,
    );
  }

  const checks = inspectGeneratedLoader(loader, manifest.version, platformNames);
  return {
    version: manifest.version,
    platformPackages: platformNames.length,
    loaderGuards: checks.length,
  };
}

const invokedPath = process.argv[1] ? pathToFileURL(resolve(process.argv[1])).href : null;
if (invokedPath === import.meta.url) {
  try {
    if (process.argv[2] === "--stage-build-bindings") {
      const packageDir = process.argv[3] ? resolve(process.argv[3]) : defaultPackageDir;
      const artifactsDir = process.argv[4]
        ? resolve(process.argv[4])
        : resolve(packageDir, "artifacts");
      const summary = await stageNapiBuildBindings(packageDir, artifactsDir);
      console.log(
        `staged identical generated bindings from ${summary.targets} targets at ${summary.version} (canonical ${summary.canonicalTarget})`,
      );
    } else {
      invariant(process.argv.length <= 3, "usage: verify-napi-release-versions.mjs [package-dir]");
      const summary = await verifyNapiReleaseVersions(
        process.argv[2] ? resolve(process.argv[2]) : defaultPackageDir,
      );
      console.log(
        `release versions OK: ${summary.version}, ${summary.platformPackages} platform packages, ${summary.loaderGuards} loader guards`,
      );
    }
  } catch (error) {
    console.error(`release version verification failed: ${error.message}`);
    process.exitCode = 1;
  }
}
